    // coupled spherical harmonics,
    // benchmarked with Mathematica.
    std::complex<double> Y_coupled(const int l, const int m, const int la, const int lb, const double theta_a, const double phi_a, const double theta_b, const double phi_b, util::WignerSymbols &wigner)
    {
        if ((abs(m) > l) || (abs(la - lb) > l) || ((la + lb) < l))
        {
            return 0;
        }
        std::complex<double> temp = 0;
        for (int ma = -la; ma <= la; ma++)
        {
            int mb = m - ma;
            if (abs(mb) > lb)
            {
                continue;
            }
            double cg = wigner.CG(2 * la, 2 * lb, 2 * l, 2 * ma, 2 * mb, 2 * m);
            std::complex<double> ya = Ylm(la, ma, theta_a, phi_a);
            std::complex<double> yb = Ylm(lb, mb, theta_b, phi_b);
            temp = temp + cg * ya * yb;
        }
        return temp;
    }

    std::complex<double> Ybra(const int l, const int m, const int la, const int lb, const double theta_a, const double phi_a, const double theta_b, const double phi_b, util::WignerSymbols &wigner)
    {
        return std::conj(Y_coupled(l, m, la, lb, theta_a, phi_a, theta_b, phi_b, wigner));
    }

    std::complex<double> Yket(const int l, const int m, const int la, const int lb, const double theta_b, util::WignerSymbols &wigner)
    {
        return Y_coupled(l, m, la, lb, 0, 0, theta_b, 0, wigner);
    }

